#!/usr/bin/env python3
"""z01 主題 v2 建置：讀 taxonomy_v2.json + feed/latest_frame.json + feed/snapshots_*.ndjson.gz
輸出 feed/trend_v2.js（window.A23_TREND_V2），並把 noscript 主題分組清單寫入 index.html 標記區。
不改寫任何歷史快照；只產生衍生檔。純標準庫，可在 Windows 直接跑：python build_trend_v2.py
"""
import glob, gzip, html, json, os, re
from datetime import datetime

BASE = os.path.dirname(os.path.abspath(__file__))
FEED = os.path.join(BASE, "feed")
TAX = json.load(open(os.path.join(BASE, "taxonomy_v2.json"), encoding="utf-8"))
TOPICS = TAX["topics"]
FALLBACK = TAX.get("fallback_topic_by_source", {})
SRC_ROWS = [s for s in TAX["sources"] if s.get("feed_source")]
FEED_SRCS = [s["feed_source"] for s in SRC_ROWS]


def _pat(kw):
    if re.fullmatch(r"[A-Za-z0-9 .\-]+", kw):
        tail = r"(?:s|es)?" if len(kw) >= 4 and not kw.endswith("s") else ""  # 長詞容許複數(tariffs/chips)
        return re.compile(r"(?<![A-Za-z])" + re.escape(kw) + tail + r"(?![A-Za-z])", re.I)
    return re.compile(re.escape(kw))


PATS = [[_pat(k) for k in t["kw"]] for t in TOPICS]


def _txt(a):
    return (a.get("title", "") or "") + " " + (a.get("title_zh") or "")


def classify(title, source):
    scores = [sum(1 for p in ps if p.search(title or "")) for ps in PATS]
    best = max(scores)
    if best > 0:
        return scores.index(best)
    return FALLBACK.get(source, -1)


def load_snapshots():
    snaps = []
    for fp in sorted(glob.glob(os.path.join(FEED, "snapshots_*.ndjson.gz"))):
        with gzip.open(fp, "rt", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    try:
                        snaps.append(json.loads(line))
                    except Exception:
                        pass
    for fp in sorted(glob.glob(os.path.join(FEED, "snapshots", "*", "*.json"))):
        try:
            with open(fp, "r", encoding="utf-8") as f:
                snaps.append(json.load(f))
        except Exception:
            pass
    return snaps


def load_timeline_slots():
    fp = os.path.join(FEED, "timeline.js")
    try:
        t = open(fp, encoding="utf-8").read()
        d = json.loads(t[t.index("{"):t.rindex("}") + 1])
        return [f["timestamp"] for f in d.get("frames", [])]
    except Exception:
        return []


def counts_of(arts):
    m = [[0] * len(FEED_SRCS) for _ in TOPICS]
    unc = 0
    for a in arts:
        src = a.get("source")
        tid = classify(_txt(a), src)
        if tid < 0 or src not in FEED_SRCS:
            unc += 1
            continue
        m[tid][FEED_SRCS.index(src)] += 1
    return m, unc


def main():
    latest = json.load(open(os.path.join(FEED, "latest_frame.json"), encoding="utf-8"))
    arts = latest.get("articles", [])
    cls = [classify(_txt(a), a.get("source")) for a in arts]

    slots = load_timeline_slots()
    by_hour = {}
    for s in load_snapshots():
        cap = (s.get("captured_at") or "")[:13]  # YYYY-MM-DD HH
        if cap and (cap not in by_hour or s["captured_at"] > by_hour[cap]["captured_at"]):
            by_hour[cap] = s
    frames = []
    for ts in slots:
        s = by_hour.get(ts[:13])
        if not s:
            frames.append({"timestamp": ts, "missing": True})
            continue
        m, unc = counts_of(s.get("articles", []))
        frames.append({"timestamp": ts, "missing": False, "counts": m, "unclassified": unc})

    out = {
        "built_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "version": TAX["version"],
        "topics": [{k: t[k] for k in ("id", "name", "color")} for t in TOPICS],
        "sources": TAX["sources"],
        "feed_sources": FEED_SRCS,
        "latest_class": cls,
        "frames": frames,
    }
    with open(os.path.join(FEED, "trend_v2.js"), "w", encoding="utf-8") as f:
        f.write("// Auto-generated by build_trend_v2.py\nwindow.A23_TREND_V2 = ")
        json.dump(out, f, ensure_ascii=False)
        f.write(";\n")

    # P1-13 noscript：依主題分組的靜態清單
    groups = {t["id"]: [] for t in TOPICS}
    unc = []
    for a, c in zip(arts, cls):
        (groups[c] if c >= 0 else unc).append(a)
    parts = ['<noscript><div class="ns-list"><h2>新聞脈動河流 · 無 JavaScript 靜態清單（%s，共 %d 則）</h2>'
             % (html.escape(latest.get("captured_at", "--")), len(arts))]
    for t in TOPICS:
        g = groups[t["id"]]
        parts.append('<h3 style="color:%s">%s（%d）</h3><ul>' % (t["color"], html.escape(t["name"]), len(g)))
        for a in g:
            parts.append('<li><b>[%s]</b> <a href="%s">%s</a></li>' % (
                html.escape(a.get("source", "")), html.escape(a.get("url", "#"), quote=True), html.escape(a.get("title_zh") or a.get("title", ""))))
        parts.append("</ul>")
    if unc:
        parts.append("<h3>未分類（%d）</h3><ul>" % len(unc))
        for a in unc:
            parts.append('<li><b>[%s]</b> <a href="%s">%s</a></li>' % (
                html.escape(a.get("source", "")), html.escape(a.get("url", "#"), quote=True), html.escape(a.get("title_zh") or a.get("title", ""))))
        parts.append("</ul>")
    parts.append("</div></noscript>")
    block = "\n".join(parts)
    ip = os.path.join(BASE, "index.html")
    if os.path.exists(ip):
        src = open(ip, encoding="utf-8").read()
        a, b = "<!-- NOSCRIPT_V2:BEGIN -->", "<!-- NOSCRIPT_V2:END -->"
        if a in src and b in src:
            new = src[:src.index(a) + len(a)] + "\n" + block + "\n" + src[src.index(b):]
            if new != src:
                open(ip, "w", encoding="utf-8").write(new)
    n_c = sum(1 for c in cls if c >= 0)
    print("trend_v2: %d 幀（有資料 %d）、最新 %d 則（已分類 %d）" % (
        len(frames), sum(1 for f in frames if not f["missing"]), len(arts), n_c))
    try:  # 突發事件（斷點）：依賴上面剛寫好的 trend_v2.js
        import build_events
        build_events.main()
    except Exception as e:
        print("[WARN] build_events 失敗（不影響河流）:", e)
    try:  # 文字雲封面條資料（依賴 events_v2.js）
        import wordcloud
        wordcloud.main()
    except Exception as e:
        print("[WARN] wordcloud 失敗（不影響河流）:", e)


if __name__ == "__main__":
    main()
